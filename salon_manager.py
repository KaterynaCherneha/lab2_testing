#Імпортуємо вбудовану бібліотеку json
#вона потрібна нам для того, щоб перетворювати наш словник із записами у текстовий формат JSON і зберігати у файл
import json

#створюємо наш власний клас помилки, який наслідується від базового класу Exception
#ми будемо викликати цю помилку, коли клієнт спробує записатися на час, який вже зайнято
class TimeSlotAlreadyBookedError(Exception):
    """Виключення: час вже зайнятий іншим клієнтом."""
    #pass означає, що ми не додаємо ніякого додаткового коду всередину цього класу
    #нам достатньо того, що він просто існує і має таку назву
    pass

#створюємо ще один власний клас помилки
#він буде викликатися, якщо ми спробуємо скасувати запис, якого не існує
class AppointmentNotFoundError(Exception):
    """Виключення: запису на цей час не знайдено."""
    pass


#оголошуємо головний клас нашої програми, який керуватиме всім салоном краси
class SalonManager:
    
    #конструктор класу.він автоматично запускається щоразу, коли ми створюємо новий об'єкт SalonManager
    def __init__(self):
        #створюємо порожній словник і зберігаємо його в атрибут об'єкта self
        #у цьому словнику ключами буде час нап., "10:00, а значеннями - імена клієнтів "Олена"
        self.appointments = {}

    #метод для створення нового запису. Приймає час time та ім'я клієнта client_name
    def book_appointment(self, time: str, client_name: str):
        #перевіряємо, чи вже існує такий час ключ у нашому словнику
        if time in self.appointments:
            #якщо час знайдено, ми штучно генеруємо raise нашу власну помилку і передаємо їй текст повідомлення
            #на цьому виконання методу зупиняється.
            raise TimeSlotAlreadyBookedError(f"Час {time} вже зайнятий!")
        
        #якщо час вільний помилка не виникла, ми створюємо новий запис у словнику
        self.appointments[time] = client_name
        
        #повертаємо True як сигнал того, що операція пройшла успішно
        return True

    #метод для скасування запису. Приймає лише час 
    def cancel_appointment(self, time: str):
        #превіряємо, чи відсутній такий час (ключ) у словнику
        if time not in self.appointments:
            #якщо запису немає, генеруємо нашу другу помилку
            raise AppointmentNotFoundError("Запису на цей час не знайдено.")
        
        #метод pop() шукає запис за ключем (time), видаляє його зі словника 
        #і одразу повертає значення (ім'я клієнта), яке там було. Ми повертаємо це ім'я
        return self.appointments.pop(time)

    #метод для отримання всього розкладу.
    def get_all_appointments(self):
        #просто повертаємо весь наш словник із поточними записами.
        return self.appointments

    #метод для збереження розкладу у файл. Приймає назву файлу
    def save_to_file(self, filename: str):
        #конструкція with open() безпечно відкриває файл у режимі 'w'
        #вона гарантує, що файл автоматично закриється після завершення роботи, навіть якщо виникне помилка
        #encoding='utf-8' потрібен, щоб українські літери (імена клієнтів) зберігалися правильно
        with open(filename, 'w', encoding='utf-8') as f:
            #json.dump бере наш словник (self.appointments) і записує його у відкритий файл (f) у форматі JSON
            json.dump(self.appointments, f)
            
        #овертаємо True як сигнал про успішне збереження файлу
        return True